import createFetchClient from 'openapi-typesafe-fetch'
import createClient from 'openapi-typesafe-react-query'
import type { paths } from './schema' // generated by openapi-typesafe

const fetchClientOptions = import.meta.env.DEV
  ? {
      // La `baseUrl` absolue est nécessaire à `Request` hors du navigateur (tests) ;
      // dans le navigateur, c'est équivalent à un chemin relatif.
      baseUrl: globalThis.location.origin,
      // `fetch` est lu à chaque appel, pas à la création du client : sinon un `vi.stubGlobal('fetch')`
      // ou le serveur MSW des tests, installés après l'import, seraient ignorés.
      fetch: (request: Request) => globalThis.fetch(request),
    }
  : {}
export const apiClient = createFetchClient<paths>(fetchClientOptions)
export const $api = createClient(apiClient)
